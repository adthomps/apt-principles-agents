#!/usr/bin/env node
// PreToolUse hook (Edit|Write|MultiEdit). Blocks writes to files that are
// generated or canonically owned, pointing at the real source instead.
//
// Enable per repo by adding to .claude/settings.json:
//   "hooks": { "PreToolUse": [{ "matcher": "Edit|Write|MultiEdit",
//     "hooks": [{ "type": "command",
//       "command": "node .claude/hooks/pretooluse-managed-file-guard.mjs" }] }] }
//
// Fail-open: any parse/IO error allows the edit. Only unambiguous managed
// globs are blocked.

import process from "node:process";

const BLOCKED = [
  { re: /(^|\/)\.apt\//, why: "This is an installed copy under .apt/. Edit the canonical file in apt-principles-agents and re-run sync." },
  { re: /(^|\/)platforms\/[^/]+\/source\/agents\//, why: "Generated agent adapter. Edit agents/<domain>/<id>.md and run `npm run build:agents`." },
  { re: /(^|\/)\.claude\/agents\/.*\.md$/, why: "Installed subagent. Edit the canonical agent in apt-principles-agents and re-run sync." },
  { re: /(^|\/)docs\/distribution\/(AGENT-CATALOG|.*-CROSSWALK)\.md$/, why: "Generated catalog. Edit the source and run the generator." },
  { re: /(^|\/)references\/agent-catalog\.json$/, why: "Generated by build-agent-adapters.mjs. Edit canonical agent frontmatter instead." },
];

let raw = "";
process.stdin.on("data", (d) => (raw += d));
process.stdin.on("end", () => {
  try {
    const input = JSON.parse(raw || "{}");
    const p = input.tool_input?.file_path || input.tool_input?.path || "";
    for (const rule of BLOCKED) {
      if (rule.re.test(p.replaceAll("\\", "/"))) {
        process.stdout.write(JSON.stringify({ decision: "block", reason: `APT managed file: ${rule.why}` }));
        return;
      }
    }
  } catch {
    // fail open
  }
});
