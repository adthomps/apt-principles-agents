function tokensTs() {
  const theme = (t) => Object.fromEntries(themeVariables(t));
  const data = { version, shared: Object.fromEntries(sharedVariables()), dark: theme("dark"), light: theme("light") };
  return `/*\n${HEADER("typed token values")}\n*/\nexport const aptDesignTokens = ${JSON.stringify(data, null, 2)} as const;\n\nexport type AptThemeName = "dark" | "light";\n`;
}

// Flat reference (references/design-tokens.json): only color values are generated; rules, aliases
// and non-color sections stay authored. Each flat key maps to a canonical dark token.
const FLAT_COLOR_MAP = {
  background: "background", surface: "card", surfaceElevated: "apt-surface-elevated", border: "border",
  borderSubtle: "apt-border-subtle", text: "foreground", textSecondary: "apt-text-secondary",
  textMuted: "muted-foreground", primary: "primary", primaryForeground: "primary-foreground",
  secondary: "secondary", secondaryForeground: "secondary-foreground", accent: "accent",
  accentForeground: "accent-foreground", danger: "destructive", dangerForeground: "destructive-foreground",
  warning: "warning", warningForeground: "warning-foreground", success: "success",
  successForeground: "success-foreground", link: "primary", focusRing: "ring", navActive: "primary",
  actionPrimary: "primary", selected: "primary", selectedSupport: "accent", glow: "apt-glow",
};
const flatHsl = (value) => `hsl(${channels(value).replace(" / ", ",").replace(/\s+/g, ",")})`;

function flatReference() {
  const file = path.join(root, "references", "design-tokens.json");
  const raw = readFileSync(file, "utf8");
  const reference = JSON.parse(raw);
  for (const [flat, canonical] of Object.entries(FLAT_COLOR_MAP)) {
    reference.tokens.color[flat] = flatHsl(tokens.color.dark[canonical].value);
  }
  for (const [index, token] of Object.entries(tokens.color.chart)) reference.tokens.color[`chart${index}`] = flatHsl(token.value);
  reference.tokens.color.overlay = flatHsl(tokens.color.dark.overlay.value);
  reference.tokens.colorLightStatus = Object.fromEntries(
    ["success", "success-foreground", "warning", "warning-foreground"].map((k) => [
      k.replace(/-(\w)/, (_m, c) => c.toUpperCase()),
      flatHsl(tokens.color.light[k].value),
    ]),
  );
  reference.designVersion = version;
  reference.source = "GENERATED color values from apt-principles-agents/design/tokens/APT-TOKENS.json by scripts/build-design.mjs (APT-019). Edit the canonical tokens, not this file's color sections.";
  return `${JSON.stringify(reference, null, 2)}\n`;
}

const outputs = {
  "design/generated/apt-tokens.css": tokensCss("light-first"),
  "design/generated/apt-tokens.dark-first.css": tokensCss("dark-first"),
  "design/generated/tailwind-preset.cjs": tailwindPreset(),
  "design/generated/apt-theme.css": tailwindV4Theme(),
  "design/generated/tokens.ts": tokensTs(),
  "design/generated/apt-preview.html": previewHtml(),
  "references/design-tokens.json": flatReference(),
};

const stale = [];
for (const [relative, content] of Object.entries(outputs)) {
  const file = path.join(root, relative);
  const current = existsSync(file) ? readFileSync(file, "utf8").replace(/\r\n/g, "\n") : null;
  if (current === content) continue;
  stale.push(relative);
  if (!checkOnly) {
    mkdirSync(path.dirname(file), { recursive: true });
    writeFileSync(file, content);
  }
}

if (checkOnly && stale.length) {
  console.error(`Design artifacts are stale (run node scripts/build-design.mjs):\n${stale.map((f) => `- ${f}`).join("\n")}`);
  process.exit(1);
}
console.log(checkOnly ? `Design artifacts current (v${version}).` : `Design artifacts written (v${version}): ${stale.length ? stale.join(", ") : "no changes"}.`);
