import fs from "node:fs";
import path from "node:path";
import { execFileSync } from "node:child_process";

// Workspace knowledge: PROJECTS.md grouping, which repos feed which knowledge source, and copied files.
// The registry is references/workspace-knowledge.json; names and descriptions live in each repo's docs/project-identity.md.

const IDENTITY = path.join("docs", "project-identity.md");
const normalize = (text) => text.replace(/\r\n/g, "\n");

export function loadKnowledge(sourceRoot) {
  return JSON.parse(fs.readFileSync(path.join(sourceRoot, "references", "workspace-knowledge.json"), "utf8"));
}

export function loadPersonas(sourceRoot) {
  return JSON.parse(fs.readFileSync(path.join(sourceRoot, "references", "persona-register.json"), "utf8"));
}

export function loadAgentIds(sourceRoot) {
  return JSON.parse(fs.readFileSync(path.join(sourceRoot, "references", "agent-catalog.json"), "utf8")).agents.map((agent) => agent.id);
}

// Persona register: cited sources must exist in the workspace and name the persona; reviewer agents must be canonical.
export function auditPersonas({ workspaceRoot, register, agentIds }) {
  const errors = [];
  const warnings = [];
  const known = new Set(agentIds);
  const ids = new Set();
  for (const persona of register.personas) {
    if (ids.has(persona.id)) errors.push(`persona ${persona.id} is listed twice`);
    ids.add(persona.id);
    for (const agent of persona.reviewerAgents) if (!known.has(agent)) errors.push(`persona ${persona.id}: unknown reviewer agent ${agent}`);
    if (persona.gap) warnings.push(`persona ${persona.id}: ${persona.gap}`);
    for (const source of persona.sources) {
      const repository = path.join(workspaceRoot, source.repository);
      if (!fs.existsSync(repository)) { errors.push(`persona ${persona.id}: repository ${source.repository} not found`); continue; }
      if (!source.path) continue;
      const file = path.join(repository, source.path);
      if (!fs.existsSync(file)) { errors.push(`persona ${persona.id}: ${source.repository}/${source.path} not found`); continue; }
      if (source.name && !normalize(fs.readFileSync(file, "utf8")).includes(source.name)) errors.push(`persona ${persona.id}: "${source.name}" not found in ${source.repository}/${source.path}`);
    }
  }
  return { errors, warnings };
}

export function readIdentity(workspaceRoot, repository) {
  const file = path.join(workspaceRoot, repository, IDENTITY);
  if (!fs.existsSync(file)) return null;
  const text = normalize(fs.readFileSync(file, "utf8"));
  const frontmatter = text.match(/^---\n([\s\S]*?)\n---\n/);
  const fields = Object.fromEntries((frontmatter?.[1] ?? "").split("\n").map((line) => line.match(/^([\w-]+):\s*(.*)$/)).filter(Boolean).map((m) => [m[1], m[2].trim()]));
  const body = text.slice(frontmatter ? frontmatter[0].length : 0).split("\n");
  const heading = body.findIndex((line) => line.startsWith("# "));
  const description = body.slice(heading + 1).map((line) => line.trim()).filter(Boolean).join(" ");
  return { folder: fields.folder, name: fields.name, status: fields.status, description };
}

export function identityRepositories(workspaceRoot) {
  return fs.readdirSync(workspaceRoot, { withFileTypes: true })
    .filter((entry) => entry.isDirectory() && fs.existsSync(path.join(workspaceRoot, entry.name, IDENTITY)))
    .map((entry) => entry.name)
    .sort((a, b) => a.localeCompare(b));
}

const cell = (value) => String(value ?? "").replace(/\|/g, "\\|");

export function renderProjects({ workspaceRoot, knowledge }) {
  const lines = [
    "---",
    "title: APT Workspace Projects",
    "version: v1",
    "status: current",
    "audience: humans-and-ai-agents",
    "visibility: internal",
    "source: generated by apt-principles-agents/scripts/workspace-knowledge.mjs",
    `last_updated: ${knowledge.last_updated}`,
    "---",
    "",
    "# APT Workspace Projects",
    "",
    "This is the summary of project names and descriptions for this workspace.",
    "",
    "**This file is generated. Don't edit it by hand.** Names and descriptions come from each project's `docs/project-identity.md`. Grouping and section notes come from `apt-principles-agents/references/workspace-knowledge.json`. Regenerate with `npm run projects:generate` in `apt-principles-agents`.",
    "",
    "Disposition (keep, complete, legacy, clarify) stays in [WORKSPACE_PROJECT_INVENTORY_2026-09-26.md](WORKSPACE_PROJECT_INVENTORY_2026-09-26.md).",
  ];
  for (const group of knowledge.groups) {
    lines.push("", `## ${group.title}`, "");
    if (group.intro) lines.push(group.intro, "");
    lines.push("| Folder | Name | Description |", "| --- | --- | --- |");
    for (const repository of group.repositories) {
      const identity = readIdentity(workspaceRoot, repository);
      lines.push(`| [${repository}](${repository}/docs/project-identity.md) | ${cell(identity?.name ?? "Missing identity")} | ${cell(identity?.description ?? "Missing docs/project-identity.md.")} |`);
    }
  }
  lines.push(
    "",
    "## Adding a project",
    "",
    "1. Create `<folder>/docs/project-identity.md` with `folder`, `name`, `status`, a title, and one description.",
    "2. Add the folder to a group in `apt-principles-agents/references/workspace-knowledge.json`. If it feeds or is fed by another repo, add it to `feeds` too.",
    "3. Run `npm run projects:generate` in `apt-principles-agents`.",
    "4. Use `status: planned` when the folder exists only to hold the identity. Use `status: unconfirmed` when the folder is real and the owner has not set the description yet.",
    "",
  );
  return lines.join("\n");
}

function git(cwd, args) {
  try {
    return execFileSync("git", ["-C", cwd, ...args], { encoding: "utf8", stdio: ["ignore", "pipe", "ignore"] }).trim();
  } catch {
    return null;
  }
}

export function auditKnowledge({ workspaceRoot, knowledge, personas = null, agentIds = [], projectsPath = path.join(workspaceRoot, "PROJECTS.md") }) {
  const errors = [];
  const warnings = [];
  if (personas) {
    const result = auditPersonas({ workspaceRoot, register: personas, agentIds });
    errors.push(...result.errors);
    warnings.push(...result.warnings);
  }
  const folderExists = (repository) => fs.existsSync(path.join(workspaceRoot, repository));

  // Identity files and grouping.
  const grouped = new Map();
  for (const group of knowledge.groups) {
    for (const repository of group.repositories) {
      if (grouped.has(repository)) errors.push(`${repository} is in groups ${grouped.get(repository)} and ${group.id}`);
      grouped.set(repository, group.id);
      if (!folderExists(repository)) { errors.push(`${repository} (group ${group.id}) does not exist in the workspace`); continue; }
      const identity = readIdentity(workspaceRoot, repository);
      if (!identity) { errors.push(`${repository} has no ${IDENTITY.replace(/\\/g, "/")}`); continue; }
      if (identity.folder !== repository) errors.push(`${repository}: identity folder is "${identity.folder}"`);
      if (!identity.name || !identity.description) errors.push(`${repository}: identity needs a name and a description`);
      if (identity.status === "unconfirmed") warnings.push(`${repository}: description not confirmed by the owner`);
    }
  }
  for (const repository of identityRepositories(workspaceRoot)) {
    if (!grouped.has(repository)) errors.push(`${repository} has an identity file but is not in any group`);
  }

  // Feeds: a knowledge repo is possibly behind when a repo feeding it has commits after the knowledge repo's last commit.
  const feeds = knowledge.feeds.map((feed) => {
    for (const repository of [feed.to, ...feed.from]) if (!folderExists(repository)) errors.push(`feeds: ${repository} does not exist in the workspace`);
    const last = folderExists(feed.to) ? git(path.join(workspaceRoot, feed.to), ["log", "-1", "--format=%ct %cI"]) : null;
    const [lastSeconds, lastCommit = null] = last ? last.split(" ") : [];
    const newer = lastCommit ? feed.from.filter(folderExists).map((repository) => ({
      repository,
      // --since is inclusive and only second-precise, so compare commit times strictly.
      commitsSince: (git(path.join(workspaceRoot, repository), ["log", "--format=%ct", `--since=${lastCommit}`, "HEAD"]) ?? "")
        .split("\n").filter((seconds) => Number(seconds) > Number(lastSeconds)).length,
    })).filter((item) => item.commitsSince > 0) : [];
    if (newer.length) warnings.push(`${feed.to} may be behind: ${newer.map((item) => `${item.repository} has ${item.commitsSince} newer commit(s)`).join(", ")}`);
    return { to: feed.to, from: feed.from, lastCommit, newerSources: newer };
  });

  // Copies must match their source of truth.
  const copies = knowledge.copies.map((entry) => {
    const source = path.join(workspaceRoot, entry.source);
    const copy = path.join(workspaceRoot, entry.copy);
    let status = "current";
    if (!fs.existsSync(source)) status = "missing-source";
    else if (!fs.existsSync(copy)) status = "missing-copy";
    else if (normalize(fs.readFileSync(source, "utf8")) !== normalize(fs.readFileSync(copy, "utf8"))) status = "drifted";
    if (status !== "current") errors.push(`copy ${entry.id}: ${status} (${entry.copy}). Refresh: ${entry.refresh}`);
    return { ...entry, status };
  });

  // PROJECTS.md must match the identity files and registry.
  let projects = "missing";
  if (fs.existsSync(projectsPath)) projects = normalize(fs.readFileSync(projectsPath, "utf8")) === renderProjects({ workspaceRoot, knowledge }) ? "current" : "stale";
  if (projects !== "current") errors.push(`PROJECTS.md is ${projects}. Run npm run projects:generate in apt-principles-agents.`);

  return { status: errors.length ? "failed" : "passed", errors, warnings, projects, feeds, copies };
}
